#!/usr/bin/env python3
"""Compile loader/loader.c and write js/loader-blob.js.

Needs only Apple/LLVM clang (no ARM linker): the object must have a single
.text section with no relocations, so it can be copied to RAM as-is.
"""
import base64, pathlib, struct, subprocess, sys, tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "loader" / "loader.c"
OUT = ROOT / "js" / "loader-blob.js"
CFLAGS = ["--target=thumbv7em-none-eabi", "-mcpu=cortex-m4", "-mthumb", "-mfloat-abi=soft",
          "-Os", "-ffreestanding", "-fno-builtin", "-fno-jump-tables", "-fno-pic", "-fropi",
          "-fno-asynchronous-unwind-tables", "-fno-unwind-tables", "-Wall", "-Werror"]


def sections(elf):
    shoff, = struct.unpack_from("<I", elf, 0x20)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", elf, 0x2E)
    raw = [struct.unpack_from("<IIIIIIIIII", elf, shoff + i * shentsize) for i in range(shnum)]
    strtab = raw[shstrndx]
    name = lambda off: elf[strtab[4] + off:elf.index(b"\0", strtab[4] + off)].decode()
    return [dict(name=name(s[0]), type=s[1], flags=s[2], off=s[4], size=s[5], link=s[6], entsize=s[9]) for s in raw]


def main():
    with tempfile.TemporaryDirectory() as d:
        obj = pathlib.Path(d) / "loader.o"
        subprocess.run(["clang", *CFLAGS, "-c", str(SRC), "-o", str(obj)], check=True)
        elf = obj.read_bytes()
    secs = sections(elf)
    alloc = [s for s in secs if s["flags"] & 2 and s["size"]]
    bad = [s["name"] for s in alloc if s["name"] not in (".text", ".ARM.exidx")]
    rels = [s["name"] for s in secs if s["type"] in (4, 9) and s["size"] and "debug" not in s["name"] and "exidx" not in s["name"]]
    if bad or rels:
        sys.exit(f"loader must be a single .text with no relocations; found {bad} {rels}")
    text = next(s for s in secs if s["name"] == ".text")
    code = elf[text["off"]:text["off"] + text["size"]]
    symtab = next(s for s in secs if s["type"] == 2)
    strs = secs[symtab["link"]]
    syms = {}
    for i in range(symtab["size"] // 16):
        st_name, st_value, _, _, _, _ = struct.unpack_from("<IIIBBH", elf, symtab["off"] + i * 16)
        n = elf[strs["off"] + st_name:elf.index(b"\0", strs["off"] + st_name)].decode()
        syms[n] = st_value & ~1
    code += b"\0" * (-len(code) % 4)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "// Generated by tools/build_loader.py from loader/loader.c. Do not edit.\n"
        f"export const LOADER = {{\n  entry: {syms['loader']:#x},\n  done: {syms['loader_done']:#x},\n"
        f"  size: {len(code)},\n  code: \"{base64.b64encode(code).decode()}\",\n}};\n")
    print(f"loader: {len(code)} bytes, entry {syms['loader']:#x}, done {syms['loader_done']:#x} -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
